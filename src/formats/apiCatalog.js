const WRAPPERS = /^(?:__isoc99_|__isoc23_|__imp_)/

/**
 * Catalogue entry for a symbol name: `{ tag, description }`, or null.
 * Accepts versioned ELF names (printf@GLIBC_2.2.5), glibc's checked and ISO
 * wrappers (__printf_chk, __isoc99_sscanf), macOS variant suffixes
 * (fopen$DARWIN_EXTSN) and Win32 A/W suffixes (CreateFileW).
 */
export function lookupApi(rawName) {
  if (!rawName) return null
  let name = rawName
  const at = name.indexOf('@')
  if (at > 0) name = name.slice(0, at)
  const dollar = name.indexOf('$')
  if (dollar > 0) name = name.slice(0, dollar)
  name = name.replace(WRAPPERS, '')
  let checked = false
  const chk = /^__(\w+)_chk$/.exec(name)
  if (chk && name !== '__stack_chk_fail' && Object.hasOwn(CATALOG, chk[1])) {
    name = chk[1]
    checked = true
  }
  let entry = Object.hasOwn(CATALOG, name) ? CATALOG[name] : null
  if (!entry && /[a-z0-9_][AW]$/.test(name)) {
    const stem = name.slice(0, -1)
    if (Object.hasOwn(CATALOG, stem)) entry = CATALOG[stem]
  }
  if (!entry) return null
  return { tag: entry[0], description: checked ? `${entry[1]} (bounds-checked variant from _FORTIFY_SOURCE)` : entry[1] }
}

export const CATALOG_SIZE = Object.keys(CATALOG).length
